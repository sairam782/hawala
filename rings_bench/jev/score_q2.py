"""score_q2.py: score question set 2 (rulings in the descriptions) on main, heldout_a and heldout_b, plus the gate,
plus a code-only rule baseline (loop, or a burst to or from 3+ distinct accounts) for honesty.

  python score_q2.py     # prints and writes out/scores_q2.md + out/scores_q2.json
"""
import json, sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE)); sys.path.insert(0, str(HERE.parent))
import score_jev as S  # noqa: E402
import facts  # noqa: E402

S.VARIANTS = ["facts", "sentences"]
OUT = HERE / "out"
SLICES = {"main": HERE.parent / "data", "heldout_a": HERE.parent / "slices" / "heldout_a", "heldout_b": HERE.parent / "slices" / "heldout_b"}


def code_rule(units):
    """ring if the code facts show a loop, or a burst to/from 3+ distinct accounts within an hour."""
    rings = false = 0
    for u in units.values():
        f = facts.compute_facts(u)
        hit = bool(f["loops"]) or any(b["distinct_counterparties"] >= 3 for b in f["bursts"])
        if u["expected"] == "ring":
            rings += hit
        else:
            false += hit
    return rings, false


def main():
    res = {}
    S.say("# Jev question set 2 (rulings in the descriptions): scores (generated by score_q2.py)\n")
    data = {}
    for tag, d in SLICES.items():
        jev, units, bench = S.load(f"{tag}_q2", d)
        data[tag] = (jev, units, bench)
        S.say(f"Ledger {tag}: {json.dumps(jev['ledger'])}")
    S.say("\n## Code-only rule for comparison (ring if a loop, or a burst to or from 3+ distinct accounts within an hour)\n")
    S.say("| slice | ring units called ring | ordinary called ring |"); S.say("|---|---|---|")
    for tag, (jev, units, bench) in data.items():
        r, f = code_rule(units)
        res[f"code_rule_{tag}"] = {"rings": r, "false": f}
        S.say(f"| {tag} | {r}/20 | {f}/40 |")
    for tag, (jev, units, bench) in data.items():
        res[f"jev_{tag}"] = S.jev_table(jev, units, f"{tag} (question set 2)")
    for tag, (jev, units, bench) in data.items():
        res[f"cal_{tag}"] = S.calibration(jev, f"{tag} (question set 2)")

    jm, um, bm = data["main"]
    S.say("\n## Gate on Sonnet's ring calls, question set 2 (threshold chosen on main v3, applied to heldout_a and heldout_b Sonnet v2)\n")
    chosen = {}
    for variant in S.VARIANTS:
        for signal in ("p_ring", "evidence_0_100"):
            table = S.gate_sweep(jm, bm, "v3", variant, signal, "main")
            best = max(table[1:], key=lambda s: (round(S.f1(s), 4), -s["threshold"]))
            chosen[(variant, signal)] = best["threshold"]
    for variant in S.VARIANTS:
        for signal, grid in (("p_ring", [0.3, 0.5, 0.6, 0.7, 0.8, 0.9, 0.95]), ("evidence_0_100", [30, 40, 50, 60, 70, 75, 80])):
            t = S.gate_sweep(jm, bm, "v3", variant, signal, "main", grid)
            S.show_gate(t, f"### main slice, Sonnet v3 gated by Jev {signal} (state variant {variant}, question set 2)")
            S.say(f"\nBest F1 threshold on main (full sweep): {chosen[(variant, signal)]}")
    S.say("\n### Chosen thresholds applied unchanged to the held-out slices (Sonnet v2 there; v3 only exists on main)\n")
    S.say("| state variant | signal | threshold | slice, Sonnet version | precision before -> after | recall before -> after | rings found before -> after | false rings before -> after |")
    S.say("|---|---|---|---|---|---|---|---|")
    applied = []
    for variant in S.VARIANTS:
        for signal in ("p_ring", "evidence_0_100"):
            t = chosen[(variant, signal)]
            for tag, ver in (("main", "v3"), ("main", "v2"), ("heldout_a", "v2"), ("heldout_b", "v2")):
                jev, units, bench = data[tag]
                runs = [r for r in bench["runs"] if r["model"] == S.SONNET and r["version"] == ver]
                if not runs:
                    S.say(f"| {variant} | {signal} | {t} | {tag} Sonnet {ver} | no Sonnet {ver} runs on this slice | | | |"); continue
                tbl = S.gate_sweep(jev, bench, ver, variant, signal, tag, [t])
                b, a = tbl[0], tbl[1]
                applied.append({"variant": variant, "signal": signal, "threshold": t, "slice": tag, "sonnet_version": ver, "runs": len(runs), "before": b, "after": a})
                S.say(f"| {variant} | {signal} | {t} | {tag} Sonnet {ver} ({len(runs)} runs) | {b['precision']:.2f} -> {a['precision']:.2f} | {b['recall']:.2f} -> {a['recall']:.2f} | "
                      f"{b['rings_found']} -> {a['rings_found']} | {b['false_rings']} -> {a['false_rings']} |")
    S.say("\n### Sonnet's own 'low' drop, and both gates together (question set 2)\n")
    S.say("| slice | Sonnet version | gate | precision | recall | rings found | false rings |"); S.say("|---|---|---|---|---|---|---|")
    both = []
    for tag, ver in (("main", "v3"), ("main", "v2"), ("heldout_a", "v2"), ("heldout_b", "v2")):
        jev, units, bench = data[tag]
        runs = [r for r in bench["runs"] if r["model"] == S.SONNET and r["version"] == ver and not r["technical_failure"]]
        if not runs:
            continue
        conf = {r["unit"]: r["confidence"] for r in runs}
        s0 = S.summarize(runs); s1 = S.summarize(S.gated(runs, lambda u: conf[u] != "low"))
        S.say(f"| {tag} | {ver} ({len(runs)} runs) | none | {s0['precision']:.2f} | {s0['recall']:.2f} | {s0['rings_found']} | {s0['false_rings']} |")
        S.say(f"| {tag} | {ver} | drop Sonnet 'low' | {s1['precision']:.2f} | {s1['recall']:.2f} | {s1['rings_found']} | {s1['false_rings']} |")
        for variant in S.VARIANTS:
            for signal in ("p_ring", "evidence_0_100"):
                t = chosen[(variant, signal)]
                J = {r["unit"]: r for r in jev["rows"] if r["variant"] == variant and "error" not in r}
                s2 = S.summarize(S.gated(runs, lambda u: conf[u] != "low" and J.get(u, {}).get(signal, 0) >= t))
                S.say(f"| {tag} | {ver} | drop 'low' AND Jev {signal} < {t} ({variant}) | {s2['precision']:.2f} | {s2['recall']:.2f} | {s2['rings_found']} | {s2['false_rings']} |")
                both.append({"slice": tag, "version": ver, "variant": variant, "signal": signal, "threshold": t, **s2})
    res.update({"gate_applied": applied, "both_gates": both, "chosen_thresholds": {f"{v}|{s}": t for (v, s), t in chosen.items()}})
    (OUT / "scores_q2.json").write_text(json.dumps(res, indent=1), encoding="utf-8")
    (OUT / "scores_q2.md").write_text("\n".join(S.LINES), encoding="utf-8")


if __name__ == "__main__":
    main()
