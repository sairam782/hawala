"""prefilter.py: Jev as a PRE-FILTER (Alex, 12:40: "only using the llms on ones that reach a certain threshold on jev").

Jev runs first on every neighborhood; only neighborhoods at or above the threshold go to the LLM (Sonnet v3 on main);
the rest are closed as ordinary with no LLM call. Per threshold: neighborhoods reaching the LLM, rings found of 20,
false rings of 40, LLM cost and latency saved against running the LLM on all 60 (per-run cost_usd and latency_ms from
bench_results.json), with Jev's own cost and latency added back. Thresholds chosen on main, applied unchanged to
heldout_a (Sonnet v2 there, since v3 was never run on it). No new Jev calls: reads out/jev_*.json and the call logs.

  python prefilter.py      # prints and writes out/prefilter.md + out/prefilter.json
"""
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
BENCH = HERE.parent
OUT = HERE / "out"
SONNET = "anthropic/claude-sonnet-5-5"
# the three Jev signals worth sweeping, (jev output tag suffix, state variant, field, label)
SIGNALS = [("_q2", "facts", "p_ring", "set 2, facts-only state, p(ring)"),
           ("_q2", "sentences", "evidence_0_100", "set 2, sentence state, evidence Score"),
           ("", "sentences", "evidence_0_100", "set 1, sentence state, evidence Score")]
GRID = {"p_ring": [0.0, 0.3, 0.5, 0.7, 0.9], "evidence_0_100": [0, 30, 40, 50, 60, 70, 75]}
LINES = []


def say(s=""):
    print(s); LINES.append(s)


def jev_cost_latency(tag, variant):
    """Mean Jev cost and median latency per call for one variant, from the call log (one call = one neighborhood)."""
    costs, lats = [], []
    for line in open(OUT / f"calls_{tag}.jsonl", encoding="utf-8"):
        r = json.loads(line)
        s = r["state"]
        v = "rows_facts" if "transfers (a transfer" in s else ("facts" if s.startswith("Facts") else "sentences")
        if v == variant:
            costs.append(r["cost_usd"]); lats.append(r["latency_ms"])
    lats.sort()
    return sum(costs) / len(costs), lats[len(lats) // 2]


def evaluate(tag, slice_dir, version, signal_tag, variant, field, thresholds):
    jev = json.load(open(OUT / f"jev_{tag}{signal_tag}.json", encoding="utf-8"))
    J = {r["unit"]: r[field] for r in jev["rows"] if r["variant"] == variant and "error" not in r}
    bench = json.load(open(slice_dir / "bench_results.json", encoding="utf-8"))
    runs = {r["unit"]: r for r in bench["runs"] if r["model"] == SONNET and r["version"] == version}
    if not runs:
        return None
    jc, jl = jev_cost_latency(f"{tag}{signal_tag}", variant)
    all_cost = sum(r["cost_usd"] for r in runs.values()); all_lat = sum(r["latency_ms"] for r in runs.values())
    rows = []
    for t in thresholds:
        sent = [u for u in runs if J.get(u, 0) >= t]
        rings = sum(1 for u in sent if runs[u]["ring_found"])
        false = sum(1 for u in sent if runs[u]["expected"] == "ordinary" and runs[u]["verdict"] == "ring")
        rings_closed = sum(1 for u in runs if u not in sent and runs[u]["expected"] == "ring")
        llm_cost = sum(runs[u]["cost_usd"] for u in sent); llm_lat = sum(runs[u]["latency_ms"] for u in sent)
        rows.append({"threshold": t, "to_llm": len(sent), "rings_found": rings, "false_rings": false, "ring_units_closed_unseen": rings_closed,
                     "llm_cost_usd": round(llm_cost, 4), "cost_saved_usd": round(all_cost - llm_cost - 60 * jc, 4),
                     "cost_saved_pct": round(100 * (all_cost - llm_cost - 60 * jc) / all_cost, 1),
                     "llm_latency_s_total": round(llm_lat / 1000, 1), "latency_saved_s_total": round((all_lat - llm_lat - 60 * jl) / 1000, 1),
                     "latency_saved_pct": round(100 * (all_lat - llm_lat - 60 * jl) / all_lat, 1)})
    return {"all_llm_cost_usd": round(all_cost, 4), "all_llm_latency_s": round(all_lat / 1000, 1), "jev_cost_per_call": round(jc, 6),
            "jev_latency_ms": jl, "version": version, "rows": rows}


def table(res, title):
    say(f"\n{title}\n")
    say(f"LLM on all 60: ${res['all_llm_cost_usd']} and {res['all_llm_latency_s']} s of model time in total; Jev adds ${60 * res['jev_cost_per_call']:.4f} and "
        f"{60 * res['jev_latency_ms'] / 1000:.1f} s for 60 calls (serial; 4 s at 8 workers).\n")
    say("| Jev threshold | neighborhoods sent to the LLM of 60 | rings found of 20 | false rings of 40 | ring units closed unseen | LLM cost saved | LLM time saved |")
    say("|---|---|---|---|---|---|---|")
    for r in res["rows"]:
        say(f"| {r['threshold']} | {r['to_llm']} | {r['rings_found']} | {r['false_rings']} | {r['ring_units_closed_unseen']} | "
            f"${r['cost_saved_usd']} ({r['cost_saved_pct']}%) | {r['latency_saved_s_total']} s ({r['latency_saved_pct']}%) |")


def main():
    out = {}
    say("# Jev as a pre-filter in front of the LLM (generated by prefilter.py)\n")
    say("Jev first on every neighborhood; the LLM sees only neighborhoods at or above the threshold; the rest are closed as "
        "ordinary with no LLM call. A threshold of 0 is the LLM on all 60 (the baseline). Thresholds chosen on main against "
        "Sonnet v3 and applied unchanged to heldout_a, where only Sonnet v2 exists. 'Ring units closed unseen' = planted rings "
        "the LLM never saw. Note that on the verdict numbers a pre-filter and the gate are the same arithmetic (a closed "
        "neighborhood and a dropped ring call both end as 'ordinary, nothing flagged'); what the pre-filter adds is the "
        "LLM calls, cost and time saved.")
    for signal_tag, variant, field, label in SIGNALS:
        key = f"{label}"
        out[key] = {}
        for tag, d, ver in (("main", BENCH / "data", "v3"), ("heldout_a", BENCH / "slices" / "heldout_a", "v2")):
            res = evaluate(tag, d, ver, signal_tag, variant, field, GRID[field])
            if res:
                out[key][tag] = res
                table(res, f"## {label}: {tag}, Sonnet {ver}")
    (OUT / "prefilter.json").write_text(json.dumps(out, indent=1), encoding="utf-8")
    (OUT / "prefilter.md").write_text("\n".join(LINES), encoding="utf-8")


if __name__ == "__main__":
    main()
